#!/usr/bin/env python3
"""Generate both host contracts from resources/native-contract.json; --check is read-only."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def release_version(value, source):
    if not isinstance(value, str) or not re.fullmatch(r'(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)', value):
        raise SystemExit(f'{source} version must be a major.minor.patch release number')
    return tuple(map(int, value.split('.')))


def outputs():
    spec = json.loads((ROOT / 'resources/native-contract.json').read_text(encoding='utf-8'))
    helper_version = release_version(spec.get('version'), 'resources/native-contract.json')
    versions = {}
    for name, pattern in (
        ('Audition Macro.lua', r'^-- @version[ \t]+(.+?)[ \t]*$'),
        ('CMakeLists.txt', r'project\(AuditionMacro\s+VERSION\s+([^\s)]+)'),
    ):
        match = re.search(pattern, (ROOT / name).read_text(encoding='utf-8'), re.MULTILINE)
        versions[name] = release_version(match[1] if match else None, name)
    if versions['CMakeLists.txt'] != helper_version:
        raise SystemExit('CMakeLists.txt version does not match resources/native-contract.json')
    # Lua-only releases can retain the last native helper. These are release
    # ordering checks; runtime compatibility is determined by feature revisions.
    if versions['Audition Macro.lua'] < helper_version:
        raise SystemExit('Audition Macro.lua package version is older than the native helper version')
    bar = spec['bar']
    quote = lambda value: json.dumps(value, ensure_ascii=False)
    header = ['// Generated by tools/generate_native_contract.py. Edit resources/native-contract.json.',
              '#pragma once', '#include <array>', '#include <cstddef>', '#include <cmath>', 'namespace amcontract {',
              'enum class Kind { missing, null_value, object, array, string, boolean, number };',
              'enum class ControlKind { button, toggle, popup };',
              'struct Control { const char* command; const char* title; const char* compact_title; ControlKind kind; int width; int compact_width; bool minimal; const char* tooltip; };',
              'struct Field { const char* name; Kind kind; bool required; };',
              f'inline constexpr std::size_t max_macros={bar["max_macros"]};',
              f'inline constexpr std::size_t max_search_groups={bar["max_search_groups"]};',
              f'inline constexpr std::size_t max_json_bytes={bar["max_json_bytes"]};']
    for key, value in bar['layout'].items():
        header.append(f'inline constexpr int {key}={value};')
    header.append('enum ControlIndex { ' + ','.join(c['command'].replace(':','_') + '=' + str(i) for i,c in enumerate(bar['controls'])) + ' };')
    header.append(f'inline constexpr int control_count={len(bar["controls"])};')
    header.append(f'inline constexpr std::array<Control,{len(bar["controls"])}> controls{{{{')
    for c in bar['controls']:
        header.append('  {' + ','.join([quote(c['command']), quote(c['title']), quote(c['compact_title']),
                      'ControlKind::' + c['kind'], str(c['width']), str(c['compact_width']),
                      str(c['minimal']).lower(), quote(c['tooltip'])]) + '},')
    header.append('}};')
    for name in ('fields', 'macro_fields', 'search_fields', 'search_group_fields', 'channel_fields', 'channel_item_fields', 'settings_fields', 'settings_value_fields', 'editor_fields', 'editor_value_fields'):
        header.append(f'inline constexpr std::array<Field,{len(bar[name])}> {name}{{{{')
        header.extend('  {' + quote(f['name']) + ',Kind::' + f['type'] + ',' + str(f['required']).lower() + '},' for f in bar[name])
        header.append('}};')
    for key, values in bar['options'].items():
        header.append(f'inline constexpr std::array<double,{len(values)}> {key}_options{{{{' + ','.join(map(str, values)) + '}};')
    for platform in ('windows', 'macos'):
        info = {'schema': spec['schema'], 'version': spec['version'], 'platform': platform,
                'features': {name: f['revision'] for name, f in spec['features'].items() if f.get('platform', platform) == platform}}
        header.append(f'inline constexpr const char* {platform}_info=R"AM({json.dumps(info, separators=(",", ":"))})AM";')
    header.extend(['inline const char* helper_info() {', '#ifdef _WIN32', '  return windows_info;', '#else', '  return macos_info;', '#endif', '}',
                   '// Adapters report JSON types; booleans are distinct from numeric 0/1 on both OSes.',
                   'template<class Value, std::size_t N> bool valid_fields(const Value& value, const std::array<Field,N>& expected) {',
                   '  if(value.kind()!=Kind::object)return false;',
                   '  for(const auto& field:expected) { const auto kind=value.child(field.name).kind();',
                   '    if(kind==Kind::missing && !field.required)continue;',
                   '    if(kind!=field.kind)return false;', '  } return true;', '}',
                   'template<class Value> bool valid_bar_state(const Value& state) {',
                   '  if(!valid_fields(state,fields))return false;',
                   '  const auto macros=state.child("macros"); if(macros.size()>max_macros)return false;',
                   '  for(std::size_t i=0;i<macros.size();++i)if(!valid_fields(macros.at(i),macro_fields))return false;',
                   '  const auto channels=state.child("channels");',
                   '  if(channels.kind()!=Kind::missing) {',
                   '    if(!valid_fields(channels,channel_fields))return false;',
                   '    const auto items=channels.child("items");if(items.size()>8)return false;',
                   '    double last=0;',
                   '    for(std::size_t i=0;i<items.size();++i) {',
                   '      const auto item=items.at(i);if(!valid_fields(item,channel_item_fields))return false;',
                   '      const double channel=item.child("channel").number();',
                   '      if(std::floor(channel)!=channel || channel<=last || channel>128)return false;',
                   '      last=channel;',
                   '    }',
                   '  }',
                   '  const auto settings=state.child("settings");',
                   '  if(settings.kind()!=Kind::missing) {',
                   '    if(!valid_fields(settings,settings_fields))return false;',
                   '    const double focus=settings.child("focus").number();',
                   '    if(std::floor(focus)!=focus || focus<0 || focus>9007199254740991.0)return false;',
                   '    const auto values=settings.child("values");if(!valid_fields(values,settings_value_fields))return false;',
                   '    const double monitor=values.child("monitor_gain_db").number();if(monitor< -60 || monitor>0)return false;',
                   '    for(const auto key:{"preview_fade_ms","fade_ms"}) { const double fade=values.child(key).number();if(fade<0 || fade>50)return false; }',
                   '  }',
                   '  const auto editor=state.child("editor");',
                   '  if(editor.kind()!=Kind::missing) {',
                   '    if(!valid_fields(editor,editor_fields) || !valid_fields(editor.child("values"),editor_value_fields))return false;',
                   '    const double focus=editor.child("focus").number(),page=editor.child("page").number();',
                   '    if(std::floor(focus)!=focus || focus<0 || focus>9007199254740991.0 || std::floor(page)!=page || page< -1 || page>4)return false;',
                   '    const auto presets=editor.child("presets");if(presets.size()<1 || presets.size()>max_macros+1)return false;',
                   '    for(std::size_t i=0;i<presets.size();++i)if(!valid_fields(presets.at(i),macro_fields))return false;',
                   '  }',
                   '  const auto search=state.child("search");',
                   '  if(search.kind()!=Kind::missing) {',
                   '    if(!valid_fields(search,search_fields))return false;',
                   '    const auto revision=search.child("revision");',
                   '    if(revision.kind()!=Kind::missing) {',
                   '      const double n=revision.number();',
                   '      if(std::floor(n)!=n || std::abs(n)>9007199254740991.0)return false;',
                   '    }',
                   '    const auto groups=search.child("groups");',
                   '    if(groups.kind()!=Kind::missing) {',
                   '      if(groups.size()>max_search_groups)return false;',
                   '      for(std::size_t i=0;i<groups.size();++i)if(!valid_fields(groups.at(i),search_group_fields))return false;',
                   '    }',
                   '  }',
                   '  return true;', '}', '} // namespace amcontract', ''])
    lua = '-- Generated by tools/generate_native_contract.py. Edit resources/native-contract.json.\nreturn require("am.json").decode([==[\n' + json.dumps(spec, ensure_ascii=False, separators=(',', ':')) + '\n]==])\n'
    return {'native/contract.h': '\n'.join(header), 'lib/am/native_contract.lua': lua}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for name, text in outputs().items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text(encoding='utf-8') != text:
                raise SystemExit(f'{name} is stale. Run python tools/generate_native_contract.py')
        else:
            path.write_text(text, encoding='utf-8')
    print('Native contract: ' + ('up to date' if args.check else 'generated'))


if __name__ == '__main__':
    main()
